import { NextResponse, type NextRequest } from "next/server";
import { timingSafeEqual } from "node:crypto";
import type { NewMessage } from "@/db/schema/audit";
import { isDuplicateMessage, messageStore } from "@/domain/messages/store";
import { logAudit } from "@/lib/audit";
import { sendDispatchAlert } from "@/lib/email";
import { recipientsFor } from "@/lib/desk-settings";
import { auditDeskAlert } from "@/lib/desk-alert-audit";
import { DESK_ALERT_KIND } from "@/lib/desk-alert-recipients.mjs";

// Inbound email webhook — Postmark's "Inbound Stream" calls this URL
// with a JSON payload representing a parsed reply. We use a path-based
// secret (`/api/email/inbound/[secret]`) rather than HMAC because
// Postmark's HMAC-signing scheme isn't on by default and a long random
// secret in the URL is equivalent in practice. The secret lives in
// `INBOUND_EMAIL_SECRET`.
//
// Threading: outbound emails carry `[QT-2026-NNNN]` or `[JN-2026-NNNN]`
// in the subject. Customer replies typically prepend `Re:` but preserve
// the bracketed code; we extract it and route to the right thread.
//
// Idempotency: Postmark retries on timeout. The `messages_inbound_provider_id_uq`
// partial unique index on `delivery_message_id` short-circuits duplicate
// deliveries — we catch the unique-violation and return 200 so Postmark
// stops retrying.

export const dynamic = "force-dynamic";
export const runtime = "nodejs";

// Match `[QT-2026-1234]` or `[JN-2026-1234]` (case-insensitive). The
// Re:/Fwd: prefix is irrelevant; we just need to find the bracketed
// code anywhere in the subject.
const SUBJECT_CODE_RE = /\[((?:QT|JN|INV)-\d{4}-\d+)\]/i;

type PostmarkInbound = {
  From?: string;
  FromFull?: { Email?: string; Name?: string };
  To?: string;
  Subject?: string;
  TextBody?: string;
  HtmlBody?: string;
  StrippedTextReply?: string;
  MessageID?: string;
  Date?: string;
};

export async function POST(
  request: NextRequest,
  { params }: { params: Promise<{ secret: string }> },
): Promise<NextResponse> {
  const expected = process.env.INBOUND_EMAIL_SECRET;
  if (!expected) {
    // Ships dark — without the secret configured, the endpoint is
    // disabled. 404 (not 503) so the route looks like it doesn't exist.
    return NextResponse.json({ error: "not found" }, { status: 404 });
  }

  // True constant-time secret check via timingSafeEqual. The prior
  // `===` shortcircuited byte-by-byte and a low-jitter attacker (e.g.
  // co-located in the same cloud region) could recover the secret one
  // character at a time. We pre-check the length to satisfy
  // timingSafeEqual's equal-length precondition (length leak is fine —
  // the secret is generated by `openssl rand -hex 32`, so 64 chars is
  // public knowledge).
  const { secret } = await params;
  const expectedBuf = Buffer.from(expected);
  const presentedBuf = Buffer.from(secret);
  if (
    presentedBuf.length !== expectedBuf.length ||
    !timingSafeEqual(presentedBuf, expectedBuf)
  ) {
    return NextResponse.json({ error: "not found" }, { status: 404 });
  }

  let payload: PostmarkInbound;
  try {
    payload = (await request.json()) as PostmarkInbound;
  } catch {
    return NextResponse.json({ error: "invalid json" }, { status: 400 });
  }

  const subject = (payload.Subject ?? "").slice(0, 500);
  const match = SUBJECT_CODE_RE.exec(subject);
  if (!match) {
    // No code in subject — we can't route the message. Log it for ops
    // visibility but ACK to Postmark so it doesn't retry.
    console.warn("[email:inbound] unmatched subject", {
      messageId: payload.MessageID,
      subject,
      from: payload.From,
    });
    // Don't silently lose it — a "yes, book it" that lost its subject
    // bracket is still a customer talking. Forward to the desk inbox.
    await forwardUnroutedToDesk("there's no request or trip reference in the subject", payload);
    return NextResponse.json({ received: true, unmatched: true });
  }

  const code = match[1].toUpperCase();
  const route = await resolveRoute(code);
  if (!route) {
    console.warn("[email:inbound] code not found in DB", {
      code,
      messageId: payload.MessageID,
      subject,
    });
    await forwardUnroutedToDesk(`reference ${code} doesn't match a request or trip`, payload);
    return NextResponse.json({ received: true, codeNotFound: true });
  }

  const fromEmail = (payload.FromFull?.Email ?? payload.From ?? "")
    .slice(0, 320)
    .toLowerCase()
    .trim();
  const body = (payload.StrippedTextReply ?? payload.TextBody ?? "").slice(0, 50_000);
  const preview = body.length > 140 ? `${body.slice(0, 139)}…` : body;
  const providerMessageId = payload.MessageID?.slice(0, 200) ?? null;

  // From-verification: Postmark inbound has no HMAC by default (the
  // path secret is the only auth), and the underlying SMTP From header
  // is trivially spoofable. Without this check, anyone who learns the
  // path secret (or who lands one phished URL on a dispatcher) can post
  // forged messages that dispatchers see as authentic customer replies
  // and act on (reroute trips, change pickup addresses). We require the
  // From address to match a known user — preferably the member on this
  // thread, but any known user is acceptable defense in depth (real
  // attackers won't have an arbitrary verified email in our users
  // table). Unknown-sender messages are logged and dropped.
  const knownSender = await resolveKnownSender(fromEmail);
  if (!knownSender) {
    console.warn("[email:inbound] dropped — sender not in users table", {
      from: fromEmail,
      code,
      messageId: providerMessageId,
    });
    // Not threaded (sender unverified — see the spoofing note above), but
    // not lost either: anonymous quote requesters aren't in `users`, and a
    // reply to their own options email used to vanish here. The desk gets
    // it flagged as UNVERIFIED instead.
    await forwardUnroutedToDesk(`the sender isn't on a JetNine account (reference ${code})`, payload);
    return NextResponse.json({ received: true, droppedUnknownSender: true });
  }

  const values: NewMessage = {
    subjectType: route.subjectType,
    subjectId: route.subjectId,
    channel: "email",
    direction: "in",
    fromAddress: fromEmail || null,
    toAddress: (payload.To ?? "").slice(0, 320) || null,
    fromUserId: knownSender.id,
    toUserId: route.toUserId ?? null,
    preview,
    body,
    isRead: false,
    deliveryStatus: "sent", // inbound = delivered, by definition
    deliveryProvider: "postmark",
    deliveryMessageId: providerMessageId,
    deliveredAt: parsedDate(payload.Date),
  };

  let inserted: { id: string } | null = null;
  try {
    inserted = (await messageStore().insertMessage(values)) ?? null;
  } catch (err) {
    // Unique-violation on the partial index = duplicate Postmark
    // delivery. 200 OK so Postmark stops retrying.
    if (isDuplicateMessage(err)) {
      return NextResponse.json({ received: true, deduped: true });
    }
    console.error("[email:inbound] insert failed", err);
    return NextResponse.json({ error: "insert failed" }, { status: 500 });
  }

  if (!inserted) {
    return NextResponse.json({ error: "insert returned nothing" }, { status: 500 });
  }

  // Audit but don't fail the webhook if audit fails — the message is
  // already in the DB; audit is best-effort metadata.
  try {
    await logAudit({
      actorUserId: null,
      actorRole: "system",
      action: `${route.subjectType}.message.inbound`,
      subjectType: route.subjectType,
      subjectId: route.subjectId,
      subjectCode: code,
      metadata: {
        messageId: inserted.id,
        from: fromEmail,
        providerMessageId,
        bodyLen: body.length,
      },
    });
  } catch (err) {
    console.error("[email:inbound] audit failed (non-fatal)", err);
  }

  // Wake the desk — before this, inbound replies landed unread in the
  // thread with nothing pointing at them.
  try {
    const staff = await recipientsFor(DESK_ALERT_KIND);
    const alert = await sendDispatchAlert({
      subject: `[${code}] Reply from ${fromEmail || "the client"}`,
      headline: "A client replied by email.",
      lines: [preview || "(empty message)", `Reference ${code}`],
      link: {
        label: "Open the thread",
        url: `https://jetnine.com/admin/${route.subjectType === "quote" ? "requests" : "trips"}/${route.subjectId}`,
      },
      to: staff,
    });
    await auditDeskAlert({
      action: `${route.subjectType}.reply.notify.email`,
      subjectType: route.subjectType,
      subjectId: route.subjectId,
      subjectCode: code,
      result: alert,
      staffRecipients: staff.length,
      extra: { channel: "email" },
    });
  } catch (err) {
    console.error("[email:inbound] desk alert failed (non-fatal)", err);
  }

  return NextResponse.json({ received: true, messageId: inserted.id });
}

// Forward an inbound email the router couldn't thread to the dispatch
// mailbox. Content is untrusted (external senders); it's presented as data
// in a desk email, never inserted into a thread.
async function forwardUnroutedToDesk(
  reason: string,
  payload: PostmarkInbound,
): Promise<void> {
  try {
    const body = (payload.StrippedTextReply ?? payload.TextBody ?? "").slice(0, 1200);
    const staff = await recipientsFor(DESK_ALERT_KIND);
    const alert = await sendDispatchAlert({
      subject: `[UNROUTED] An email we couldn't match — ${reason}`,
      headline: "An email came in that we couldn't match to a request or trip.",
      lines: [
        `From: ${payload.From ?? "unknown"}`,
        `Subject: ${payload.Subject ?? "(none)"}`,
        `Why: ${reason}.`,
        "Their message (unverified, first 1,200 characters):",
        body || "(empty)",
      ],
      to: staff,
    });
    // The reason is not stored: two of its three texts carry a reference code taken from the
    // sender's subject line, so only the outcome is recorded (OPS-279, step 5).
    await auditDeskAlert({
      action: "inbound_email.unrouted.notify.email",
      subjectType: "system",
      result: alert,
      staffRecipients: staff.length,
    });
  } catch (err) {
    console.error("[email:inbound] unrouted forward failed (non-fatal)", err);
  }
}

type RouteTarget = {
  subjectType: "quote" | "trip";
  subjectId: string;
  toUserId: string | null;
};

async function resolveRoute(code: string): Promise<RouteTarget | null> {
  // The lookup (quote code first, then trip code, a JN- code can be either) lives in the
  // message store (OPS-164), Postgres or D1 by dbTarget().
  return messageStore().threadByCode(code);
}

/**
 * Match the inbound From address against our users table. We accept any
 * known user (not just the thread's member) so two-cardholder accounts
 * and dispatcher-to-dispatcher replies thread correctly. Returns null
 * when the From doesn't map to anyone we know — those messages get
 * dropped to prevent spoofed instructions from reaching dispatchers.
 */
async function resolveKnownSender(fromEmail: string): Promise<{ id: string } | null> {
  if (!fromEmail) return null;
  return messageStore().userIdByEmail(fromEmail);
}

/**
 * `new Date(payload.Date)` can produce an Invalid Date on malformed
 * Date headers (forwarded mail with broken headers, third-party scanner
 * mangling). The truthy-check fallback `payload.Date ? new Date(...) :
 * new Date()` doesn't help because "garbage" is truthy. Validate via
 * getTime() and fall back to now() on NaN.
 */
function parsedDate(raw: string | undefined): Date {
  if (!raw) return new Date();
  const d = new Date(raw);
  return Number.isFinite(d.getTime()) ? d : new Date();
}
